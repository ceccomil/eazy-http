    var code = $$"""
      private static Encoding ResolveEncoding(
        ClientContext context,
        EazyClientOptions options)
      {
        // 1. Fixed per-client encoding
        if (options.Encodings.TryGetValue(context.ClientName, out var encoding))
        {
          return encoding;
        }

        // 2. Resolver fallback
        if (options.ResolveEncoding is { } resolver)
        {
          var resolved = resolver(context);
          if (resolved is not null)
          {
            return resolved;
          }
        }

        // 3. Default
        return Encoding.UTF8;
      }

      private static JsonSerializerOptions ResolveSerializer(
        ClientContext context,
        EazyClientOptions options)
      {
        // 1. Fixed per-client serializer
        if (options.SerializerOptions.TryGetValue(context.ClientName, out var serializer))
        {
          return serializer;
        }

        // 2. Resolver fallback
        if (options.ResolveSerializer is { } resolver)
        {
          var resolved = resolver(context);
          if (resolved is not null)
          {
            return resolved;
          }
        }

        // 3. Default
        return new JsonSerializerOptions(JsonSerializerDefaults.Web)
        {
          PropertyNamingPolicy = JsonNamingPolicy.CamelCase
        };
      }

      private static ImmutableArray<RequestHeader> ResolveHeaders(
        ClientContext context,
        EazyClientOptions options)
      {
        // 1. Fixed per-client headers
        if (options.PersistentHeaders.TryGetValue(context.ClientName, out var headers) && headers is not null)
        {
          return [.. headers];
        }

        // 2. Resolver fallback
        if (options.ResolveHeaders is { } resolver)
        {
          var resolved = resolver(context);
          if (resolved is not null)
          {
            return [.. resolved];
          }
        }

        // 3. Default: empty
        return [];
      }

      private static RetryConfiguration{{nullable}} ResolveRetry(
        ClientContext context,
        EazyClientOptions options)
      {
        // 1. Fixed per-client retry-config
        if (options.Retries.TryGetValue(context.ClientName, out var cfg))
        {
          return cfg;
        }

        // 2. Resolver fallback
        if (options.ResolveRetry is { } resolver)
        {
          return resolver(context);
        }

        // 3. Default: no retry
        return null;
      }
      """;

    return code;
  }

  private static string GetBuildUrl(bool nullableEnabled)
  {
    var nullable = nullableEnabled
      ? "?"
      : "";

    var code = $$"""
      private string BuildUrl(
        string route,
        HttpQuery{{nullable}} query = null)
      {
        // Absolute URL -> ignore BaseAddress
        if (!string.IsNullOrWhiteSpace(route) &&
          route.StartsWith("http", StringComparison.OrdinalIgnoreCase))
        {
          var absolute = route.Trim();

          return query is null
            ? absolute
            : absolute + query.ToString();
        }

        var baseUrl = $"{HttpClient.BaseAddress}";

        if (!string.IsNullOrWhiteSpace(baseUrl))
        {
          baseUrl = baseUrl.TrimEnd('/');
        }

        route ??= string.Empty;
        route = route.TrimStart('/');

        var url = string.IsNullOrWhiteSpace(baseUrl)
          ? route
          : $"{baseUrl}/{route}";

        if (query is not null)
        {
          url += query.ToString();
        }

        return url;
      }
      """;

