  public void Initialize(IncrementalGeneratorInitializationContext context)
  {
    context.DefaultSourceOutputRegistration(Execute);
  }

  private static void Execute(
    SourceProductionContext context,
    ImmutableArray<EazyClientOptionsDefinition> options,
    bool nullableEnabled)
  {
    if (options.IsDefaultOrEmpty)
    {
      return;
    }
    
    foreach (var o in options)
    {
      GenerateClients(context, o, nullableEnabled);
    }
  }

  private static void GenerateClients(
    SourceProductionContext context,
    EazyClientOptionsDefinition options,
    bool nullableEnabled)
  {
    foreach (var client in options.Clients)
    {
      GenerateClient(
        context, 
        client, 
        options,
        nullableEnabled);
    }
  }

  private static void GenerateClient(
    SourceProductionContext context,
    HttpClientDefinition definition,
    EazyClientOptionsDefinition options,
    bool nullableEnabled)
  {
    var @namespace = options
      .NamespacePrefix
      .GetEazyHttpClientNamespace();

    var interfaceBase = definition.OptionalHeadersInMethods
      ? nameof(IEazyHttpClient)
      : nameof(ISimpleEazyHttpClient);

    var interfaceMethods = definition.OptionalHeadersInMethods
      ? GetFullInterfaceImplementation(nullableEnabled)
      : GetSimpleInterfaceImplementation(nullableEnabled);

    var nullable = nullableEnabled
      ? "?"
      : "";

    var code = $$"""
      {{AutoGeneratedComment}}
      {{nullableEnabled.ToNullableDirectiveIfEnabled()}}

      {{GetUsings()}}

      namespace {{@namespace}};

      {{GeneratedCodeAttribute}}
      public interface I{{definition.Name}} : {{interfaceBase}};

      {{GeneratedCodeAttribute}}
      internal sealed class {{definition.Name}} : I{{definition.Name}}
      {
        private readonly {{nameof(EazyClientOptions)}} _options;
        private readonly IServiceProvider _serviceProvider;
        private readonly JsonSerializerOptions _serializerOptions;
        private readonly Encoding _encoding;
        private readonly RetryConfiguration{{nullable}} _retryConfiguration;

        public HttpClient HttpClient { get; }
          
        public {{definition.Name}}(
          HttpClient httpClient,
          IOptions<{{nameof(EazyClientOptions)}}> options,
          IServiceProvider serviceProvider)
        {
          HttpClient = httpClient;
          _options = options.Value;
          _serviceProvider = serviceProvider;

          {{GetBaseAddressInitializer(definition)}}

          var context = new ClientContext(
            nameof({{definition.Name}}), 
            serviceProvider);

          _encoding = ResolveEncoding(context, _options);
          _serializerOptions = ResolveSerializer(context, _options);
          var headers = ResolveHeaders(context, _options);
          _retryConfiguration = ResolveRetry(context, _options);

          foreach (var header in headers)
          {
            HttpClient
              .DefaultRequestHeaders
              .TryAddWithoutValidation(header.Name, header.Value);
          }
        }

        {{interfaceMethods}}

        {{GetResolverMethods(nullableEnabled)}}

        {{GetBuildUrl(nullableEnabled)}}

        {{GetDeserializer(nullableEnabled)}}

        {{GetSendCore(nullableEnabled)}}

        {{GetSendNoResult(nullableEnabled)}}

        {{GetSendAndDeserialize(nullableEnabled)}}

        {{GetSendEnvelope(nullableEnabled)}}

        private sealed record RawResponse(
          HttpStatusCode StatusCode,
          HttpResponseHeaders Headers,
          HttpContentHeaders ContentHeaders,
          byte[] ContentBytes,
          bool IsSuccessStatusCode);
      }
      """;


    context.AddSource(
      definition.GetEazyHttpClientFilename(@namespace),
      code.GetFormattedCode());
  }

